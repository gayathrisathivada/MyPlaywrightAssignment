// Squares in Reverse Order
let num = 10;
for (let i = num; i >= 1; i--)      
{
    let square = i * i;   //Square
    console.log("Square of " + i + " = " + square);
}

/*Initializes i with the value of num, which is 10.
i >= 1 – Checks whether i is greater than or equal to 1. If true, the loop executes.
i-- – Decreases the value of i by 1 after each iteration  */